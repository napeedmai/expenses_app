        WHERE name = 'SEND_EXPENSE_MAIL' AND INSTR(LOWER(text), 'e.type') > 0)    AS ref_type,
       (SELECT COUNT(*) FROM user_source
        WHERE name = 'SEND_EXPENSE_MAIL' AND INSTR(LOWER(text), 'e.claim_for') > 0) AS ref_claim_for,
       (SELECT COUNT(*) FROM user_source
        WHERE name = 'SEND_EXPENSE_MAIL'
