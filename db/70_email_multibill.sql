--
--   SEND_EXPENSE_MAIL      145  PL/SQL: SQL Statement ignored
--   SEND_EXPENSE_MAIL      147  ORA-00904: "E"."BILL_NO": invalid identifier
--   PROCESS_EXPENSE_ACTION  54  PLS-00905: object SEND_EXPENSE_MAIL is invalid
--
-- ...and because ORDS will not run a resource whose PL/SQL is invalid, every
-- protected endpoint answered a bare 403 with no body. Two hours went into
-- roles and privilege patterns, both of which were correct throughout. The
-- fault dictionary entry in DEPLOYMENT.md 12 says exactly this and it should
-- have been the first thing checked.
--
-- ON PROD IT IS WORSE, because it is silent. Section 3 of script 64 never
-- executed there -- SQL Commands skipped it -- so BILL_NO and TYPE still exist
-- on EXPENSES, the procedure still compiles, and every approval email has been
-- going out with an empty bill number and no bill list at all. A reviewer is
-- being asked to approve a total with nothing behind it.
--
--
-- WHAT CHANGES
-- ------------
-- 1. Claim-level fields come from CLAIM_FOR, not TYPE/BILL_NO.
--
-- 2. The claim table shows ONE money figure: the USD total. EXPENSES.AMOUNT is
--    now SUM(items.amount) across bills that may be in different currencies,
--    so printing it beside a single currency code would be a fabrication --
--    4500 INR when one of the bills was in EUR. Per-bill amounts appear in
--    their own currency, in the bill table.
--
-- 3. A bill table is added to both the plain-text and the HTML body: item no,
--    type, description, bill no, bill date, period, amount, USD, receipt --
--    with a total row, and a line explaining the USD-only total when the bills
--    are in more than one currency.
--
-- Everything else is byte-for-byte from 62_email_autonomous_read_fix.sql: the
-- TO/CC matrix, the actor-role parameter, the passed-in uncommitted values, the
-- no-manager and manager-has-no-email notes, the mail log. Those were hard won
-- and are not being retyped from memory -- this file was generated by patching
-- 62, not by rewriting it.
--
--
-- ORDER MATTERS. send_expense_mail must compile before process_expense_action,
-- which calls it in four places. Reversing them gives PLS-00306 / PLS-00905.
-- That has bitten this project twice.
